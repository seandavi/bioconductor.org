"""Does the Astro build publish everything nanoc would from this repo?

    python3 -m pipeline.parity [DIST]     # default astro/dist; exit 1 on gaps

Expected outputs are enumerated the way nanoc's Rules route them: every page
body in content/ at its URL's index.html, every file in assets/ and every
downloadable file beside the pages in content/ at its own path. Each must exist
in the build, or be listed in GONE with the reason.
(Bioconductor/bioconductor.org#438)
"""

import os
import sys

import re

# nanoc's routing, kept here rather than imported so the check outlives the
# converter, which the freeze removes (FREEZE.md).
BODY_EXT = (".md", ".html", ".haml")
GENERATED = re.compile(r"^/help/bioc-views/")  # pages nanoc filled from package data


def url_for(rel):
    """`about/index.html` -> `/about/`, `help/faq.md` -> `/help/faq/`."""
    parts = rel.rsplit(".", 1)[0].split("/")
    if parts[-1] == "index":
        parts = parts[:-1]
    return "/" + "/".join(parts) + "/" if parts else "/"

# Not published on purpose. Paths are site-absolute.
GONE = {
    "/developers/rss-feeds/gitlog.xml": "went with /developers/gitlog/ (#435)",
    "/developers/rss-feeds/gitlog.release.xml": "went with /developers/gitlog/ (#435)",
    # Replaced by src/pages/help/search/ (Pagefind); nanoc's queried master's Solr.
    "/help/search/index.html": "replaced by the Pagefind search page",
    # Generated by src/pages/robots.txt.js; upstream's blocks /packages/release/.
    "/robots.txt": "generated",
}
# Pages dropped in #435 (dashboard, gitlog, help wanted, publications) are gone
# from content/, so they aren't expected; the edge answers 301/410 for them at
# cutover (seandavi/bioc-infrastructure#187).


def expected(repo="."):
    """Every path nanoc would publish from this checkout."""
    out = set()
    content = os.path.join(repo, "content")
    for dirpath, _, files in os.walk(content):
        for fn in files:
            rel = os.path.relpath(os.path.join(dirpath, fn), content).replace(os.sep, "/")
            stem, ext = os.path.splitext(fn)
            if rel.startswith("_partials/"):
                continue  # fragments inlined into pages after the freeze, not pages
            if ext in BODY_EXT:
                url = url_for(rel)
                if not GENERATED.match(url):
                    out.add(url + "index.html")
            elif ext == ".yaml":
                continue  # sidecars, and the event records that have no page of their own
            elif rel.startswith("style/") or rel == "sitemap.xml":
                continue  # compiled or templated by nanoc, not copied
            else:
                out.add("/" + rel)
    assets = os.path.join(repo, "assets")
    for dirpath, _, files in os.walk(assets):
        for fn in files:
            out.add("/" + os.path.relpath(os.path.join(dirpath, fn), assets).replace(os.sep, "/"))
    return out


def missing(dist, repo="."):
    return sorted(p for p in expected(repo) - set(GONE) if not os.path.exists(dist + p))


def main(argv=None):
    dist = (argv or sys.argv[1:] or ["astro/dist"])[0]
    gaps = missing(dist)
    exp = expected()
    print("[parity] %d paths nanoc would publish, %d excluded on purpose, %d missing"
          % (len(exp), len(exp & set(GONE)), len(gaps)), file=sys.stderr)
    for p in gaps:
        print("  missing: " + p, file=sys.stderr)
    stale = sorted(set(GONE) - exp)
    for p in stale:
        print("  GONE lists %s, which nanoc no longer publishes; remove it" % p, file=sys.stderr)
    return 1 if gaps or stale else 0


if __name__ == "__main__":
    sys.exit(main())
